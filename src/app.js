import express from 'express';
import cors from 'cors'; import helmet from 'helmet'; import rateLimit from 'express-rate-limit';
import { env } from './config/env.js';
import { requestId } from './middleware/request-id.js';
import { notFound } from './middleware/not-found.js';
import { errorHandler } from './middleware/error-handler.js';
import { apiRouter } from './routes/api.js';
export const app=express();
app.disable('x-powered-by'); app.use(helmet());
app.use(cors({origin:env.CORS_ORIGIN.split(',').map(v=>v.trim())}));
app.use(express.json({limit:'1mb'})); app.use(requestId);
app.use(rateLimit({windowMs:env.RATE_LIMIT_WINDOW_MS,limit:env.RATE_LIMIT_MAX}));
app.get('/health',(_req,res)=>res.json({status:'ok'}));
app.use('/api/v1',apiRouter); app.use(notFound); app.use(errorHandler);
